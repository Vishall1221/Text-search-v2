"""V2 staged lexical matching, adapted to catalog-only rows and controlled synonym OR groups."""
from __future__ import annotations

import math
import re
from dataclasses import dataclass
from itertools import combinations

from config.settings import settings

_WORD = re.compile(r"[^\w]", re.UNICODE)
MAX_TERMS = 8
RANK_FUNCS = {"ts_rank_cd": "ts_rank_cd", "ts_rank": "ts_rank"}


def clean_terms(terms: list[str]) -> list[str]:
    out = []
    for t in terms:
        c = _WORD.sub("", t)
        if c and c not in out:
            out.append(c)
    return out[:MAX_TERMS]


def min_match(n_terms: int) -> int:
    """Terms a document must contain in the relaxed stages (<= 2 terms: any one)."""
    if n_terms <= 2:
        return 1
    return max(1, math.ceil(settings.lex_min_match_ratio * n_terms))


def _any_of(terms: list[str], size: int) -> str:
    """tsquery text: documents containing at least ``size`` of ``terms`` (OR of all AND-combinations)."""
    return " | ".join("(" + " & ".join(c) + ")" for c in combinations(terms, size))


def stages(terms: list[str], relax: bool) -> list[tuple[str, str]]:
    """[(stage name, tsquery text)] from strictest to loosest."""
    terms = clean_terms(terms)
    if not terms:
        return []
    n = len(terms)
    out = [("and", " & ".join(terms))]
    if not relax or n < 2:
        return out
    need = min(min_match(n), n)
    if need >= n:                                   # a ratio of 1.0 means "all words": nothing to relax
        return out
    if n >= 3:
        out.append(("but_one", _any_of(terms, n - 1)))
    if need < n - 1 or n == 2:                      # (for n == need + 1 the but_one stage is already this stage)
        out.append(("relaxed", _any_of(terms, need)))
    return out


@dataclass(frozen=True)
class LexQuery:
    sql: str
    params: dict


def _rank_fn() -> str:
    return RANK_FUNCS.get(settings.lex_rank_fn, "ts_rank_cd")


def main_query(*, generation, tsquery, window, allowed):
    from app.vocab import LEXICAL_SYNONYMS
    # Query operators are generated by stages(); raw user input never enters SQL.
    tsquery = re.sub(r"\b\w+\b", lambda m: "(" + " | ".join(LEXICAL_SYNONYMS[m.group()]) + ")"
                     if m.group() in LEXICAL_SYNONYMS else m.group(), tsquery)
    sql = f"""WITH q AS (SELECT to_tsquery('english',%(q)s) AS tsq)
        SELECT d.show_id AS asset_key, max({_rank_fn()}(d.tsv_main,q.tsq,%(norm)s)) AS score
        FROM schema_v2_large.search_doc d,q
        WHERE d.generation_id=%(gen)s AND d.tsv_main @@ q.tsq
        {"AND d.show_id=ANY(%(allowed)s)" if allowed is not None else ""}
        GROUP BY d.show_id ORDER BY score DESC,d.show_id LIMIT %(window)s"""
    return LexQuery(sql,dict(q=tsquery,gen=generation,norm=settings.lex_rank_norm,allowed=allowed,window=window))
